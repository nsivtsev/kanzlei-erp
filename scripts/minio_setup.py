"""Local-only MinIO bootstrap. Secrets travel via stdin/environment, never CLI output."""

import argparse
import json
import os
import secrets
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CREDENTIAL_KEYS = (
	"LOCAL_MINIO_ROOT_USER",
	"LOCAL_MINIO_ROOT_PASSWORD",
	"LOCAL_S3_ACCESS_KEY",
	"LOCAL_S3_SECRET_KEY",
	"LOCAL_MINIO_TEST_ACCESS_KEY",
	"LOCAL_MINIO_TEST_SECRET_KEY",
)


def ensure_credentials(path):
	"""Append one credential set without rotating or evaluating existing .env content."""
	content = path.read_text() if path.exists() else ""
	values = {}
	for line in content.splitlines():
		key, sep, value = line.partition("=")
		if sep and key.strip() in CREDENTIAL_KEYS:
			if key.strip() in values:
				raise ValueError("Duplicate local MinIO credentials in .env")
			values[key.strip()] = value.strip().strip("\"'")
	missing = []
	for group in (CREDENTIAL_KEYS[:4], CREDENTIAL_KEYS[4:]):
		present = [key for key in group if key in values]
		if present and (len(present) != len(group) or not all(values[key] for key in present)):
			raise ValueError(
				"Local MinIO credential set is incomplete; restore the existing .env credentials"
			)
		if not present:
			missing.extend(group)
	if missing:
		generated = {key: secrets.token_hex(24) for key in missing}
		values.update(generated)
		with open(path, "a", opener=lambda filename, flags: os.open(filename, flags, 0o600)) as handle:
			os.fchmod(handle.fileno(), 0o600)
			if content and not content.endswith("\n"):
				handle.write("\n")
			handle.write("\n# Local S3 credentials (generated by setup-minio.sh; never use in production)\n")
			for key, value in generated.items():
				handle.write(f"{key}={value}\n")
	else:
		path.chmod(0o600)
	return values


def local_settings(credentials):
	return {
		"enabled": 0,
		"bucket": "stb-golke-local",
		"aws_key": credentials["LOCAL_S3_ACCESS_KEY"],
		"aws_secret": credentials["LOCAL_S3_SECRET_KEY"],
		"endpoint_url": "http://minio:9000",
		"signature_version": "s3v4",
		"flat": 1,
		"root_folder": "local/development.localhost/drive",
		"kanzlei_s3_region": "us-east-1",
		"kanzlei_s3_addressing_style": "path",
		"kanzlei_s3_public_endpoint": "http://localhost:9002",
		"kanzlei_s3_prefix": "local/development.localhost",
	}


def validate_current_settings(current, access_key):
	if (
		current.get("enabled")
		or current.get("endpoint_url") not in (None, "", "http://minio:9000")
		or current.get("bucket") not in (None, "", "stb-golke-local")
		or current.get("aws_key") not in (None, "", access_key)
	):
		raise ValueError(
			"Refusing to overwrite existing S3 configuration; configure local storage explicitly"
		)


PROVISION = r"""
set -eu
umask 077
export MC_CONFIG_DIR="$(mktemp -d)"
trap 'rm -rf "$MC_CONFIG_DIR"' EXIT
mc alias set local http://127.0.0.1:9000 "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null 2>&1
mc mb --ignore-existing local/stb-golke-local >/dev/null
mc anonymous set none local/stb-golke-local >/dev/null
cat > "$MC_CONFIG_DIR/app-policy.json" <<'POLICY'
{"Version":"2012-10-17","Statement":[{"Effect":"Allow","Action":["s3:GetBucketLocation","s3:ListBucket","s3:ListBucketMultipartUploads"],"Resource":["arn:aws:s3:::stb-golke-local"]},{"Effect":"Allow","Action":["s3:GetObject","s3:PutObject","s3:DeleteObject","s3:AbortMultipartUpload","s3:ListMultipartUploadParts"],"Resource":["arn:aws:s3:::stb-golke-local/local/development.localhost/*"]}]}
POLICY
mc admin user add local "$LOCAL_S3_ACCESS_KEY" "$LOCAL_S3_SECRET_KEY" >/dev/null 2>&1
mc admin policy create local kanzlei-local-app "$MC_CONFIG_DIR/app-policy.json" >/dev/null
mc admin policy attach local kanzlei-local-app --user "$LOCAL_S3_ACCESS_KEY" >/dev/null
mc mb --ignore-existing local/stb-golke-test >/dev/null
mc anonymous set none local/stb-golke-test >/dev/null
sed 's/stb-golke-local/stb-golke-test/g; s#local/development.localhost#tests/s3-test.localhost#g' \
    "$MC_CONFIG_DIR/app-policy.json" > "$MC_CONFIG_DIR/test-policy.json"
mc admin user add local "$LOCAL_MINIO_TEST_ACCESS_KEY" "$LOCAL_MINIO_TEST_SECRET_KEY" >/dev/null 2>&1
mc admin policy create local kanzlei-local-test "$MC_CONFIG_DIR/test-policy.json" >/dev/null
mc admin policy attach local kanzlei-local-test --user "$LOCAL_MINIO_TEST_ACCESS_KEY" >/dev/null
"""

CONFIGURE = r"""
import json, os, sys
import frappe
from minio_setup import validate_current_settings
settings = json.load(sys.stdin)
os.chdir("/workspace/development/frappe-bench/sites")
frappe.init(site="development.localhost", sites_path="/workspace/development/frappe-bench/sites")
frappe.connect()
try:
    frappe.set_user("Administrator")
    doc = frappe.get_single("Drive Disk Settings")
    if doc.enabled:
        print("Existing enabled S3 configuration preserved; no files or settings changed.")
    else:
        validate_current_settings(doc.as_dict(), settings["aws_key"])
        for field in settings:
            if not doc.meta.has_field(field):
                raise RuntimeError("Install/migrate Kanzlei S3 custom fields before configuring MinIO")
        # Keep the current disk root while inactive; migration activation changes it safely.
        settings.pop("root_folder")
        settings.pop("flat")
        doc.update(settings)
        doc.save(ignore_permissions=True)
        frappe.db.commit()
        print("Local S3 connection configured; S3 remains disabled. Existing files are unchanged.")
finally:
    frappe.destroy()
"""


def main(argv=None):
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument(
		"--credentials-only", action="store_true", help="Prepare gitignored .env before docker compose"
	)
	parser.add_argument(
		"--skip-site-config",
		action="store_true",
		help="Provision storage only, without touching ERP settings",
	)
	args = parser.parse_args(argv)
	credentials = ensure_credentials(ROOT / ".env")
	if args.credentials_only:
		print("Local MinIO credentials are ready in .env (values hidden).")
		return
	compose = [
		"docker",
		"compose",
		"--env-file",
		str(ROOT / ".env"),
		"-f",
		str(ROOT / ".devcontainer/docker-compose.yml"),
	]
	subprocess.run([*compose, "up", "-d", "--build", "--wait", "--wait-timeout", "120", "minio"], check=True)
	subprocess.run([*compose, "exec", "-T", "minio", "sh"], input=PROVISION, text=True, check=True)
	if not args.skip_site_config:
		subprocess.run(
			[
				*compose,
				"exec",
				"-T",
				"frappe",
				"bash",
				"-lc",
				"cd /workspace/development/frappe-bench && PYTHONPATH=/workspace/scripts env/bin/python -c "
				+ shlex.quote(CONFIGURE),
			],
			input=json.dumps(local_settings(credentials)),
			text=True,
			check=True,
		)
	print("Private local bucket stb-golke-local is ready; console: http://localhost:9001")
	print("No storage backend was enabled and no application files were migrated.")


if __name__ == "__main__":
	try:
		main()
	except (ValueError, subprocess.CalledProcessError) as error:
		# Do not include subprocess stdin or settings in errors.
		print(
			str(error)
			if isinstance(error, ValueError)
			else "Local MinIO setup command failed; inspect service logs.",
			file=sys.stderr,
		)
		raise SystemExit(1)
